/** The axes this app actually uses: a provider id from `golive.yaml` that is not empty. */
function axesUsed(ctx: Ctx): Array<{ axis: Axis; provider: string; providerTitle: string }> {
  const out: Array<{ axis: Axis; provider: string; providerTitle: string }> = [];
  for (const axis of AXES) {
    const provider = ctx.config.stack[axis];
    if (!provider) continue;
    const adapter = adapterById(provider, ctx.adapters);
    out.push({ axis, provider, providerTitle: adapter?.title ?? GUIDED.find((g) => g.id === provider)?.title ?? provider });
  }
  return out;
}
